<?php

namespace App\Modules\Platform\Console;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Schema;

/**
 * Design artefacts from the migrated database (roadmap 5.4): Mermaid ERDs
 * (an overview plus one diagram per module) and the schema SQL. Run it on
 * the MySQL database after migrating, so the documents never drift from the
 * code:
 *
 *   php artisan docs:schema
 */
class DocumentSchema extends Command
{
    protected $signature = 'docs:schema
        {--diagrams= : Folder for the ERDs (default docs/diagrams/erd)}
        {--sql= : File for the schema SQL (default schema/aqdesk_schema.sql)}';

    protected $description = 'Write the ERDs and the schema SQL from the migrated database';

    /** Laravel's own tables: in the SQL, left out of the diagrams. */
    private const FRAMEWORK = 'Framework';

    /** Tables from Laravel's own migrations that belong to a module. */
    private const OWNED = ['users' => 'Identity'];

    public function handle(): int
    {
        $root = dirname(base_path());
        $diagrams = $this->option('diagrams') ?: $root.'/docs/diagrams/erd';
        $sql = $this->option('sql') ?: $root.'/schema/aqdesk_schema.sql';

        $modules = $this->tablesByModule();
        $tables = $this->describe(array_merge(...array_values($modules)));

        File::ensureDirectoryExists($diagrams);
        File::delete(File::glob($diagrams.'/*.mmd'));   // numbering shifts when a module gains its first table
        File::ensureDirectoryExists(dirname($sql));

        $features = array_filter($modules, fn ($m) => $m !== self::FRAMEWORK, ARRAY_FILTER_USE_KEY);
        $files = ['00-overview' => $this->overview($features, $tables)];
        $n = 1;
        foreach ($features as $module => $names) {
            $files[sprintf('%02d-%s', $n++, strtolower($module))] = $this->moduleDiagram($module, $names, $tables);
        }

        $index = ["# AQDesk — Entity Relationship Diagrams\n", 'Generated by `php artisan docs:schema` from the migrated database ('.count($tables).' tables). '
            .'GitHub renders the diagrams below; the `.mmd` files open in any Mermaid editor.'."\n"];
        foreach ($files as $name => $mermaid) {
            File::put("$diagrams/$name.mmd", $mermaid);
            $index[] = '## '.$this->titleOf($name, $features)."\n\n```mermaid\n".$mermaid."```\n";
        }
        File::put("$diagrams/README.md", implode("\n", $index));
        File::put($sql, $this->schemaSql($modules));

        $this->info(count($tables).' tables → '.count($files).' diagrams in '.$diagrams.' and '.$sql);

        return self::SUCCESS;
    }

    /** @return array<string, array<int, string>> module => tables, from where each table's migration lives */
    private function tablesByModule(): array
    {
        $owner = [];
        $sources = [self::FRAMEWORK => database_path('migrations')];
        foreach (File::directories(app_path('Modules')) as $dir) {
            $sources[basename($dir)] = $dir.'/Database/Migrations';
        }
        foreach ($sources as $module => $dir) {
            foreach (File::isDirectory($dir) ? File::files($dir) : [] as $file) {
                preg_match_all("/Schema::create\\('([a-z0-9_]+)'/", $file->getContents(), $m);
                foreach ($m[1] as $table) {
                    $owner[$table] = self::OWNED[$table] ?? $module;
                }
            }
        }

        $existing = Schema::getTableListing(Schema::getCurrentSchemaListing(), schemaQualified: false);
        $modules = [];
        foreach ($existing as $table) {
            if ($table !== 'migrations' && ! str_starts_with($table, 'sqlite_')) {
                $modules[$owner[$table] ?? self::FRAMEWORK][] = $table;
            }
        }
        // Identity first (everything points at users), then alphabetical; framework last.
        uksort($modules, fn ($a, $b) => [$a !== 'Identity', $a === self::FRAMEWORK, $a] <=> [$b !== 'Identity', $b === self::FRAMEWORK, $b]);

        return array_map(function ($t) { sort($t); return $t; }, $modules);
    }

    /** @return array<string, array{columns: array, foreign: array, unique: array<int, string>}> */
    private function describe(array $names): array
    {
        $tables = [];
        foreach ($names as $table) {
            $unique = [];
            foreach (Schema::getIndexes($table) as $index) {
                if ($index['unique'] && ! $index['primary'] && count($index['columns']) === 1) {
                    $unique[] = $index['columns'][0];
                }
            }
            $tables[$table] = [
                'columns' => Schema::getColumns($table),
                'foreign' => Schema::getForeignKeys($table),
                'unique'  => $unique,
            ];
        }

        return $tables;
    }

    /** Every module's tables and how they connect, without columns. */
    private function overview(array $modules, array $tables): string
    {
        $out = "---\ntitle: AQDesk — all modules (relationships only)\n---\nerDiagram\n";
        foreach ($modules as $names) {
            foreach ($names as $table) {
                $out .= $this->relations($table, $tables);
            }
        }

        return $out;
    }

    /** One module's tables with their columns; tables of other modules appear as names only. */
    private function moduleDiagram(string $module, array $names, array $tables): string
    {
        $out = "---\ntitle: AQDesk — {$module} module\n---\nerDiagram\n";
        foreach ($names as $table) {
            $out .= $this->relations($table, $tables);
        }
        foreach ($names as $table) {
            $out .= "    {$table} {\n";
            $fks = collect($tables[$table]['foreign'])->pluck('columns')->flatten()->all();
            foreach ($tables[$table]['columns'] as $col) {
                $keys = array_filter([
                    $col['name'] === 'id' ? 'PK' : null,
                    in_array($col['name'], $fks, true) ? 'FK' : null,
                    in_array($col['name'], $tables[$table]['unique'], true) ? 'UK' : null,
                ]);
                $type = preg_replace('/[^a-z0-9_]/', '', strtolower($col['type_name'])) ?: 'text';
                $out .= "        {$type} {$col['name']}".($keys ? ' '.implode(', ', $keys) : '').($col['nullable'] ? ' "nullable"' : '')."\n";
            }
            $out .= "    }\n";
        }

        return $out;
    }

    /** Mermaid lines for the foreign keys of one table: parent ||--o{ child. */
    private function relations(string $table, array $tables): string
    {
        $out = '';
        foreach ($tables[$table]['foreign'] as $fk) {
            $parent = $fk['foreign_table'];
            if (! isset($tables[$parent])) {
                continue;
            }
            $column = $fk['columns'][0];
            $nullable = collect($tables[$table]['columns'])->firstWhere('name', $column)['nullable'] ?? false;
            $one = in_array($column, $tables[$table]['unique'], true) ? '|' : '{';
            $out .= "    {$parent} ".($nullable ? '|o' : '||').'--o'.$one." {$table} : \"{$column}\"\n";
        }

        return $out;
    }

    private function titleOf(string $file, array $modules): string
    {
        $slug = substr($file, 3);

        return $slug === 'overview' ? 'Overview — all modules' : (collect(array_keys($modules))->first(fn ($m) => strtolower($m) === $slug) ?? $slug).' module';
    }

    /** CREATE TABLE statements grouped by module, from the database itself. */
    private function schemaSql(array $modules): string
    {
        $mysql = in_array(DB::getDriverName(), ['mysql', 'mariadb'], true);
        $out = "-- =====================================================================\n"
            ."--  AQDesk — database schema (".($mysql ? 'MySQL 8' : DB::getDriverName()).")\n"
            ."--  Generated by `php artisan docs:schema` from the migrated database.\n"
            ."--  `php artisan migrate --seed` builds this structure with demo data;\n"
            ."--  import this file only if you want the empty structure directly.\n"
            ."-- =====================================================================\n\n"
            .($mysql ? "SET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS = 0;\n\n" : 'PRAGMA foreign_keys = OFF;'."\n\n");

        foreach ($modules as $module => $names) {
            $out .= "-- ---------------------------------------------------------------------\n-- {$module}\n-- ---------------------------------------------------------------------\n\n";
            foreach ($names as $table) {
                $create = $mysql
                    ? DB::selectOne("SHOW CREATE TABLE `{$table}`")->{'Create Table'}
                    : DB::selectOne("SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?", [$table])->sql;
                $create = preg_replace('/ AUTO_INCREMENT=\d+/', '', $create);
                $out .= ($mysql ? "DROP TABLE IF EXISTS `{$table}`;\n" : "DROP TABLE IF EXISTS \"{$table}\";\n").$create.";\n\n";
            }
        }

        return $out.($mysql ? "SET FOREIGN_KEY_CHECKS = 1;\n" : 'PRAGMA foreign_keys = ON;'."\n");
    }
}
